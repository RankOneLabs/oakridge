/** Regenerates extractor registration keys from the compiled launchable catalog. */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CoreClient, compileWorkflow } from "../src/core-client/client";
import { BLOCKER_ARTIFACT } from "../src/core-client/core-types";
import { readLaunchableCatalog, resolveDefinition } from "../src/runtime/definition-store";
import { parsedArtifactSchemaVersion } from "../src/adapters/observation-schema-version";

interface ArtifactKey {
  readonly workflow: string;
  readonly definition_id?: string;
  readonly stage: string;
  readonly artifact: string;
  readonly schema_version: string;
}
type StageKeys = { [stage: string]: { [artifact: string]: ArtifactKey } };
const root = resolve(import.meta.dir, "../..");
const catalog = readLaunchableCatalog();
if (!catalog.ok) throw new Error(JSON.stringify(catalog.error));
const startup = CoreClient.start();
if (!startup.ok) throw new Error(JSON.stringify(startup.error));
const core = startup.value;
const keys: { [workflow: string]: StageKeys } = {};
let blocker: ArtifactKey | undefined;
try {
  for (const [workflow, { definition_id }] of Object.entries(catalog.value)) {
    const definition = resolveDefinition(definition_id);
    if (!definition.ok) throw new Error(JSON.stringify(definition.error));
    const compiled = await compileWorkflow(core, { workflow: definition.value.source, prompts: definition.value.prompts, operations: definition.value.operations });
    if (!compiled.ok) throw new Error(JSON.stringify(compiled.error));
    keys[workflow] = Object.fromEntries(Object.entries(compiled.value.workflow.stages).map(([stage, declared]) => {
      const artifacts = Object.entries(declared.artifacts).flatMap(([artifact]) => {
        const schema_version = parsedArtifactSchemaVersion(compiled.value.workflow, stage, artifact);
        if (!schema_version) throw new Error(`No resolved schema for ${workflow}.${stage}.${artifact}`);
        if (artifact === BLOCKER_ARTIFACT) {
          if (blocker && blocker.schema_version !== schema_version) throw new Error("Core blocker schemas disagree");
          blocker = { workflow: "$core", stage: "*", artifact, schema_version };
          return [];
        }
        return [[artifact, { workflow, definition_id, stage, artifact, schema_version }] as const];
      });
      return [stage, Object.fromEntries(artifacts)];
    }));
  }
} finally { core.close(); }
if (!blocker) throw new Error("No core blocker schema in the launchable catalog");
keys.$core = { "*": { [BLOCKER_ARTIFACT]: blocker } };
const outputPaths = ["oakridge-dbos/src/adapters/artifact-versions.generated.ts", "observation/src/producers/oakridge/artifact-versions.ts"];
const literals = JSON.stringify(keys, null, 2).replace(/"(?:[^"\\]|\\.)*"/g,
  (token) => "'" + token.slice(1, -1).replaceAll("'", "\\'") + "'");
const content = "// Generated by bun oakridge-dbos/scripts/generate-artifact-versions.ts; never edit.\n"
  + `export type ArtifactKey = { readonly workflow: string; readonly definition_id?: string; readonly stage: string; readonly artifact: string; readonly schema_version: string };\n`
  + "export const ARTIFACT_KEYS = " + literals + " as const;\n"
  + "export const ARTIFACT_KEY_LIST: readonly ArtifactKey[] = Object.values(ARTIFACT_KEYS).flatMap((stages) =>\n"
  + "  Object.values(stages).flatMap((artifacts) => Object.values(artifacts)));\n";
const extractorDir = resolve(root, "observation/src/producers/oakridge/extractors");
const extractorModules = readdirSync(extractorDir).filter((entry) => entry.endsWith(".ts") && !entry.endsWith(".generated.ts"))
  .sort().map((entry) => entry.slice(0, -3));
const extractorAliases = extractorModules.map((_, index) => `registrations${index}`);
const extractors = "// Generated by bun oakridge-dbos/scripts/generate-artifact-versions.ts; never edit.\n"
  + extractorModules.map((module, index) => `import { registrations as ${extractorAliases[index]} } from "./${module}";\n`).join("")
  + `\nexport const extractorRegistrations = [${extractorAliases.map((alias) => `...${alias}`).join(", ")}];\n`;
const output = new Map(outputPaths.map((path) => [resolve(root, path), content]));
output.set(resolve(extractorDir, "index.generated.ts"), extractors);
for (const [path, text] of output) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== text) throw new Error(`${path} has drifted; regenerate it`);
  } else writeFileSync(path, text);
}
