/** The development workflow's definition projection, generated by oakridge-dbos/scripts/generate-pwa-definition-fixture.ts. */
const developmentDefinition = JSON.parse(
  readFileSync(resolve(import.meta.dirname, "development-definition.json"), "utf8"),
) as OperatorDefinitionBundle;

export function makeDevelopmentRootFields(): readonly InputField[] {
  const root = developmentDefinition.units.find((unit) => unit.key === developmentDefinition.root);
  const shape = developmentDefinition.schemas.find((schema) => schema.key === root?.input_schema)?.shape;
  if (shape?.kind !== "record") throw new Error("Development root input is not a record");
  return shape.fields.map((field) => ({ field, schema: developmentDefinition.schemas.find((schema) => schema.key === field.schema) }));
}

export function makeDevelopmentSchemas(): readonly OperatorSchema[] { return developmentDefinition.schemas; }
export function makeDevelopmentBundle(): OperatorDefinitionBundle { return developmentDefinition; }

