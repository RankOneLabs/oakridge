/** Regenerates current identities from the exact compiled, launchable contract. */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { CoreClient, compileWorkflow } from "../src/core-client/client";
import { readLaunchableCatalog, resolveDefinition } from "../src/runtime/definition-store";
import { parsedArtifactSchemaVersion } from "../src/adapters/observation-schema-version";
const root = resolve(import.meta.dir, "../..");
const catalog = readLaunchableCatalog();
if (!catalog.ok) throw new Error(JSON.stringify(catalog.error));
const entry = catalog.value.development;
if (!entry) throw new Error("development is not launchable");
const definition = resolveDefinition(entry.definition_id);
if (!definition.ok) throw new Error(JSON.stringify(definition.error));
const startup = CoreClient.start();
if (!startup.ok) throw new Error(JSON.stringify(startup.error));
const core = startup.value;
const compiled = await compileWorkflow(core, { workflow: definition.value.source, prompts: definition.value.prompts, operations: definition.value.operations });
core.close();
if (!compiled.ok) throw new Error(JSON.stringify(compiled.error));
const workflow = compiled.value.workflow;
const artifacts = [
  { schema: "analysis_body", stage: "analysis", artifact: "analysis" },
  { schema: "spec_body", stage: "analysis", artifact: "spec" },
  { schema: "plan_body", stage: "planning", artifact: "plan" },
  { schema: "brief_body", stage: "brief", artifact: "brief" },
  { schema: "assessment_body", stage: "cohort", artifact: "assessment" },
] as const;
const versions = Object.fromEntries(artifacts.map(({ schema, stage, artifact }) => {
  const version = parsedArtifactSchemaVersion(workflow, stage, artifact);
  if (!version) throw new Error(`No version for ${stage}.${artifact}`);
  return [schema, { version, is_distinct: true }];
}));
const content = "// Generated by bun oakridge-dbos/scripts/generate-artifact-versions.ts; never edit.\n"
  + "export const DEVELOPMENT_ARTIFACT_VERSIONS = " + JSON.stringify(versions, null, 2) + " as const;\n";
for (const relativePath of ["oakridge-dbos/src/adapters/development-artifact-versions.ts", "observation/src/producers/oakridge/artifact-versions.ts"]) {
  const path = resolve(root, relativePath);
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== content) throw new Error(`${relativePath} has drifted; run this generator`);
  } else writeFileSync(path, content);
}
