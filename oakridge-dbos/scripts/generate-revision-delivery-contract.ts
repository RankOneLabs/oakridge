import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import ts from "typescript";

const root = resolve(import.meta.dir, "../..");
function declarations(relativePath: string, select: (node: ts.TypeAliasDeclaration | ts.InterfaceDeclaration) => boolean): string[] {
  const file = ts.createSourceFile(relativePath, readFileSync(resolve(root, relativePath), "utf8"), ts.ScriptTarget.Latest, true);
  return file.statements.flatMap((node) =>
    (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) && select(node) ? [node.getText(file)] : []);
}
const inputBinding = declarations("oakridge-dbos/src/core-client/core-types.ts", (node) => node.name.text === "InputBinding");
if (inputBinding.length !== 1) throw new Error("Missing generated core InputBinding type");
const delivery = declarations("oakridge-dbos/src/adapters/revision-delivery.ts", (node) =>
  node.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword) ?? false);
const content = "// Generated by bun oakridge-dbos/scripts/generate-revision-delivery-contract.ts; never edit.\n"
  + [...inputBinding, ...delivery].join("\n\n") + "\n";
const target = resolve(root, "observation/src/ingest/dbos-revision-delivery.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== content) throw new Error("DBOS revision delivery contract has drifted; regenerate it");
} else writeFileSync(target, content);
