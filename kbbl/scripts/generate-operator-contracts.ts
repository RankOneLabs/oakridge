/**
 * Generates kbbl/core/pwa/oakridge/operator-contracts/ from the operator API
 * the backend declares in oakridge-dbos/src/http/operator-api.ts.
 *
 * Every type the API references is copied from its one backend declaration
 * (projections, storage rows, generated core contracts) with every name
 * prefixed `Operator`. Branded ids become `string` and `Date` becomes
 * `string`, which is what both serialize to. See contract-generator.ts.
 *
 * Each declaration lands in the file mirroring its backend module, so
 * projections/unit-view.ts generates operator-contracts/projections/unit-view.ts.
 */
import { BLOCKER_REVIEW, VALIDATION_REVIEW } from "../../oakridge-dbos/src/core-client/core-types";
import { ARTIFACT_KEYS } from "../../oakridge-dbos/src/adapters/artifact-versions.generated";
import { resolve } from "node:path";
import { writeContracts } from "./contract-generator";

const development = ARTIFACT_KEYS.development;
const versions = Object.fromEntries(Object.entries({ analysis_body: development.analysis.analysis, spec_body: development.analysis.spec,
  plan_body: development.planning.plan, brief_body: development.brief.brief, assessment_body: development.cohort.assessment })
  .map(([schema, key]) => [schema, { version: key.schema_version, is_distinct: true }]));

const root = resolve(import.meta.dir, "../..");
writeContracts({
  name: "generate-operator-contracts",
  root,
  api: resolve(root, "oakridge-dbos/src/http/operator-api.ts"),
  backend: resolve(root, "oakridge-dbos/src"),
  output: resolve(root, "kbbl/core/pwa/oakridge/operator-contracts"),
  prefix: "Operator",
  // Identities are generated from the compiled pinned backend contract.
  additionalFiles: new Map([["artifact-versions.ts", "// Generated by generate-operator-contracts.ts; never edit.\n"
    + "export const OPERATOR_CURRENT_ARTIFACT_VERSIONS = " + JSON.stringify(versions, null, 2) + " as const;\n"],
    ["blocker.ts", "// Generated by generate-operator-contracts.ts from the core BLOCKER_REVIEW; never edit.\nexport const BLOCKER_REVIEW = " + JSON.stringify(BLOCKER_REVIEW) + ";\n"], ["validation.ts", "// Generated by generate-operator-contracts.ts from the core VALIDATION_REVIEW; never edit.\n"
    + "export const VALIDATION_REVIEW = " + JSON.stringify(VALIDATION_REVIEW) + ";\n"]]),
  brands: { kind: "erase", primitives: resolve(root, "oakridge-dbos/src/domain/primitives.ts") },
  header: "// Generated from oakridge-dbos/src/http/operator-api.ts. Run bun kbbl/scripts/generate-operator-contracts.ts.\n"
    + "// The PWA intentionally imports no backend source at runtime or typecheck time.\n\n",
}, process.argv);
