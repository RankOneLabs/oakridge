/** A unit whose one artifact has a latest revision with the given body. */
export function makeUnitWithArtifact(options: UnitArtifactFixtureOptions): OperatorUnitView {
  const revision = makeArtifactRevision({ id: options.revision_id ?? "revision-1", body: options.body,
    artifact_key: options.artifact_key, created_at: options.created_at ?? "2026-07-01T09:00:00Z" });
  return makeUnitView({ artifacts: [makeArtifact({ artifact_key: options.artifact_key, schema: options.schema ?? options.artifact_key,
    latest_revision: revision })], ...options.unit });
}

